export type Rich = string; // **тод** гэж тэмдэглэсэн хэсгийг тодоор харуулна

export type Block =
  | { kind: "text"; text: Rich }
  | { kind: "timeline"; items: { period: string; title: string; text: Rich }[] }
  | { kind: "cards"; items: { title: string; text: Rich }[] }
  | { kind: "terms"; items: { term: string; sub?: string; text: Rich }[] }
  | { kind: "compare"; items: { title: string; sub: string; points: Rich[] }[] }
  | { kind: "stats"; items: [string, string][] }
  | { kind: "quote"; text: Rich }
  | { kind: "pricebox" }
  | { kind: "image"; src: string; alt: string; width: number; height: number; caption?: string }
  | { kind: "logos"; items: { src: string; alt: string; width: number; height: number; label: string }[] }
  | { kind: "table"; head: [string, string, string]; rows: [string, Rich, Rich][] }
  | { kind: "flow"; items: { title: string; sub?: string }[]; caption?: Rich }
  | { kind: "list"; items: Rich[] }
  | { kind: "heading"; text: string }
  | {
      kind: "apps";
      items: { name: string; tag: string; url: string; free?: boolean; recommended?: boolean; uses: Rich[] }[];
    };

export type Section = {
  id: string;
  title: string;
  blocks: Block[];
};

export type Lesson = {
  slug: string;
  number: number;
  title: string;
  summary: string;
  sections: Section[];
};

